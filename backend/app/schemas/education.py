"""Pydantic schemas for Financial Education, Glossary, and Calculators."""

from typing import List, Literal, Optional
from pydantic import Field
from app.schemas.common import APIBaseModel


class SourceCitation(APIBaseModel):
    """Source reference for RAG educational answer."""
    id: str
    title: str
    publisher: str
    url: Optional[str] = None
    confidence_score: Optional[float] = None


class ChatMessage(APIBaseModel):
    """Chat message representation matching Education ChatAssistant."""
    id: str
    sender: Literal["user", "assistant"]
    content: str
    timestamp: str
    sources: Optional[List[SourceCitation]] = []


class CalculatorRequest(APIBaseModel):
    """Payload to compute quantitative financial formula."""
    calculator_type: Literal["sip", "cagr", "drawdown", "fd"] = Field(description="Formula type")
    principal: float = Field(default=100000.0, ge=0)
    rate: float = Field(default=12.0, description="Annual rate percentage")
    tenure_years: float = Field(default=5.0, gt=0)
    monthly_sip: Optional[float] = Field(default=10000.0, ge=0)
    peak_value: Optional[float] = None
    trough_value: Optional[float] = None


class CalculationResult(APIBaseModel):
    """Single display result field for calculators."""
    label: str
    value: str
    subtext: Optional[str] = None


class CalculatorResponse(APIBaseModel):
    """Outputs generated by the educational calculator."""
    calculator_type: str
    results: List[CalculationResult]
    explanation: str


class GlossaryItem(APIBaseModel):
    """Financial concept glossary term."""
    term: str
    category: str
    definition: str
    statutory_reference: Optional[str] = None
