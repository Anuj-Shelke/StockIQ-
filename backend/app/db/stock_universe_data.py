def get_all_stocks() -> List[Dict]:
    """Retrieve full stock universe catalog."""
    return COMPREHENSIVE_STOCK_UNIVERSE


def get_stock_by_symbol(symbol: str) -> Optional[Dict]:
    """Find stock by exact or clean symbol (case-insensitive)."""
    sym = symbol.strip().upper()
    for s in COMPREHENSIVE_STOCK_UNIVERSE:
        if s["symbol"].upper() == sym:
            return s
        if s["symbol"].split(".")[0].upper() == sym:
            return s
    return None


def search_stocks(
    query: Optional[str] = None,
    exchange: Optional[str] = None,
    sector: Optional[str] = None,
    market_cap: Optional[str] = None,
    limit: int = 100,
) -> List[Dict]:
    """Filter stocks by text query, exchange, sector, and market cap tier."""
    results = []
    q_low = query.strip().lower() if query else None
    ex_up = exchange.strip().upper() if exchange else None
    sec_low = sector.strip().lower() if sector else None
    mc_low = market_cap.strip().lower() if market_cap else None

    for s in COMPREHENSIVE_STOCK_UNIVERSE:
        if ex_up and s.get("exchange", "").upper() != ex_up:
            continue
        if sec_low and sec_low not in s.get("sector", "").lower():
            continue
        if mc_low and mc_low not in s.get("market_cap_category", "").lower():
            continue
        if q_low:
            sym_match = q_low in s["symbol"].lower()
            name_match = q_low in s["name"].lower()
            sec_match = q_low in s.get("sector", "").lower()
            if not (sym_match or name_match or sec_match):
                continue
        results.append(s)
        if len(results) >= limit:
            break

    return results
