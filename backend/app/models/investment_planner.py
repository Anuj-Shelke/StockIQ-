"""SQLAlchemy ORM models for AI Personal Investment Planner & Portfolio Optimizer."""

import uuid
from sqlalchemy import (
    Column,
    DateTime,
    ForeignKey,
    JSON,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.orm import relationship

from app.db.base import Base, GUID


class PlannerProfile(Base):
    """Persisted financial profile inputs for an investor."""
    __tablename__ = "planner_profiles"

    id = Column(GUID(), primary_key=True, default=uuid.uuid4)
    user_id = Column(GUID(), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)

    # Financial details
    age = Column(Numeric(5, 0), nullable=False)
    occupation = Column(String(100), nullable=True)
    monthly_income = Column(Numeric(15, 2), nullable=False)
    monthly_expenses = Column(Numeric(15, 2), nullable=False)
    monthly_savings = Column(Numeric(15, 2), nullable=False)
    emergency_fund = Column(Numeric(15, 2), default=0.0)
    existing_investments = Column(Numeric(15, 2), default=0.0)
    debt_obligations = Column(Numeric(15, 2), default=0.0)
    financial_dependents = Column(Numeric(3, 0), default=0)
    current_investable_capital = Column(Numeric(15, 2), nullable=False)

    # Investment preferences & goals
    primary_goal = Column(String(100), nullable=False)
    target_amount = Column(Numeric(15, 2), nullable=True)
    target_years = Column(Numeric(5, 1), default=5.0)
    investment_horizon_category = Column(String(50), default="3-5 years")
    risk_tolerance = Column(String(50), default="Moderate")  # Very Low, Low, Moderate, High
    required_liquidity = Column(String(50), default="Moderate")  # High, Moderate, Low
    max_acceptable_loss_pct = Column(Numeric(5, 2), default=15.0)
    investment_style = Column(String(50), default="LUMP_SUM")  # LUMP_SUM, SIP, HYBRID, STAGGERED
    monthly_sip_amount = Column(Numeric(15, 2), default=0.0)

    # Preferences in JSON
    preferred_asset_classes = Column(JSON, default=list)
    preferred_sectors = Column(JSON, default=list)
    preferred_stocks = Column(JSON, default=list)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=True)

    # Relationships
    user = relationship("User", back_populates="planner_profiles")
    plans = relationship("InvestmentPlanRecord", back_populates="profile", cascade="all, delete-orphan")


class InvestmentPlanRecord(Base):
    """Saved, reproducible investment plan generated by the AI Investment Planner."""
    __tablename__ = "investment_plans"

    id = Column(GUID(), primary_key=True, default=uuid.uuid4)
    user_id = Column(GUID(), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    profile_id = Column(GUID(), ForeignKey("planner_profiles.id", ondelete="SET NULL"), nullable=True)

    plan_name = Column(String(200), default="Personalized Investment Plan")
    status = Column(String(50), default="ACTIVE")  # ACTIVE, ARCHIVED, REVISED

    # Comprehensive snapshot & calculation outputs
    profile_snapshot = Column(JSON, nullable=False)
    suitability_assessment = Column(JSON, nullable=False)
    asset_allocation = Column(JSON, nullable=False)
    stock_allocations = Column(JSON, nullable=False)
    fd_plan = Column(JSON, nullable=False)
    gold_plan = Column(JSON, nullable=False)
    wealth_projections = Column(JSON, nullable=False)
    risk_metrics = Column(JSON, nullable=False)
    tax_estimates = Column(JSON, nullable=False)
    timeline_milestones = Column(JSON, nullable=False)
    alternative_portfolios = Column(JSON, nullable=False)
    explainability_insights = Column(JSON, nullable=False)

    notes = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=True)

    # Relationships
    user = relationship("User", back_populates="investment_plans")
    profile = relationship("PlannerProfile", back_populates="plans")
